class Api:
    def __init__(self, key, model=None):
        self.key = key
        self.model = model or os.getenv("OPENAI_MODEL", "gpt-4.1-mini")

    def ask(self, prompt, context, tokens):
        payload = {
            "model": self.model,
            "messages": [{"role": "system", "content": prompt},
                         {"role": "user", "content": json.dumps(context, ensure_ascii=False)}],
            "response_format": {"type": "json_object"},
            "max_completion_tokens": tokens,
        }
        request = Request(
            "https://api.openai.com/v1/chat/completions", json.dumps(payload).encode(),
            {"Content-Type": "application/json", "Authorization": f"Bearer {self.key}"},
        )
        try:
            with urlopen(request, timeout=180) as response:
                data = json.load(response)
        except HTTPError as error:
            raise RuntimeError(f"OpenAI HTTP {error.code}") from None
        choice = data["choices"][0]
        if choice.get("finish_reason") != "stop":
            raise InvalidPlan("OpenAI не завершил ответ")
        return json.loads(choice["message"]["content"])


def extract(api, state, question, message, has_menu, prompt_question=""):
    data = api.ask(INTERVIEW, {"question": question, "prompt_question": prompt_question,
                              "answers": state, "menu_exists": has_menu, "message": message}, 2200)
    raw = data.get("answers")
    patch = clean_patch(raw) if isinstance(raw, dict) else {}
    revision = data.get("revision")
    clarification = data.get("clarification")
    return (patch, revision.strip()[:1500] if isinstance(revision, str) else "",
            clarification.strip()[:800] if isinstance(clarification, str) else "")


def make_plan(api, state, today, previous=None, revision=""):
    days, limit, _ = period_budget(state, today)
    context = {"answers": state, "people": dict(enumerate(names(state), 1)),
               "stores": names_of_stores(state), "days": days, "limit_rub": limit,
               "meal_order": [MEALS[i - 1] for i in state["meals"]]}
    if previous:
        context["previous_plan"] = previous
    if revision:
        context["revision"] = revision
    try:
        plan = validate(api.ask(MENU, context, 23500), state, days)
    except (InvalidPlan, json.JSONDecodeError) as error:
        correction = {**context, "correction": f"Прошлый ответ отклонён: {str(error)[:160]}. Верни полный JSON."}
        plan = validate(api.ask(MENU, correction, 26000), state, days)
    _, cost = basket(plan)
    if limit is not None and cost > limit:
        try:
            affordable = validate(api.ask(MENU, {
                **context, "previous_plan": plan,
                "correction": (
                    f"Корзина по целым упаковкам {cost} ₽ при лимите {limit} ₽. "
                    "Используй аналогичные недорогие продукты, размеры упаковок и общие запасы, "
                    "сохраняя ограничения и достаточные порции. При точечной просьбе пользователя "
                    "не изменяй другие блюда и соблюдай её. Верни полный JSON."
                )
            }, 23500), state, days)
            if basket(affordable)[1] < cost:
                return affordable
        except (InvalidPlan, json.JSONDecodeError, OSError, RuntimeError):
            pass  # The first validated plan is still usable.
    return plan
